        "if skorost_x > 0:\n"
        "    skorost_x = max(0.0, skorost_x - TRENIE * dt)\n"
        "elif skorost_x < 0:\n"
        "    skorost_x = min(0.0, skorost_x + TRENIE * dt)\n",
