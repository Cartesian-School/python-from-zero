def build_01_first_program() -> None:
    nb = NotebookBuilder()
    nb.md("""\
# 03-01 · Создание и запуск программ

Практика к разделу [«Создание и запуск программ на Python»](../../site/chapters/glava-03/03-01-sozdanie-i-zapusk-programm.html).""")
    nb.md("## Цель\n\nПочувствовать, как код превращается в результат — здесь роль «файла и запуска» "
          "играет ячейка кода.")
