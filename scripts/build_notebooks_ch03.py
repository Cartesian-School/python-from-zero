    nb.md("## Краткое напоминание\n\nВ настоящем `.py`-файле код запускают командой "
          "`python имя_файла.py`. Здесь для практики каждая ячейка — это как маленькая отдельная "
          "программа.")
    nb.md("## Рабочий пример")
    nb.code('''print("Привет, Python!")''')
    nb.md("## Эксперимент 1\n\nИзмените текст приветствия на своё.")
    nb.code('''print("Привет, Cartesian School!")''')
    nb.md("## Эксперимент 2\n\nДобавьте вторую строку `print()` с вашим именем.")
