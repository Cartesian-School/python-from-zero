def page(name: str, title: str, lede: str, body: str, *, description: str | None = None) -> str:
    index = next(i for i, entry in enumerate(PAGES) if entry[0] == name)
    prev_href, prev_title = PAGES[index - 1] if index > 0 else (None, None)
    if index + 1 < len(PAGES):
        next_href, next_title = PAGES[index + 1]
    else:
        next_href, next_title = "../../predmetnyj-ukazatel.html", "Предметный указатель"
    return render_page(
        page_title=title,
        description=description or lede,
        depth=2,
        breadcrumb=[("Python с нуля", "../../index.html"), (f"Глава 24. {CHAPTER.title}", "index.html"), (title, "")],
        kicker=KICKER,
        h1=title,
        lede=lede,
        body_html=body,
        sidebar_groups=sidebar(name),
        nav=PageNav(prev_href=prev_href, prev_label=prev_title, next_href=next_href, next_label=next_title),
    )


def write(name: str, output: str) -> None:
    path = OUT_DIR / name
    normalized = "\n".join(line.rstrip() for line in output.splitlines()) + "\n"
    path.write_text(normalized, encoding="utf-8")
    print(f"Записано: {path.relative_to(ROOT)}")


