def level_ladder(rows: list[tuple[str, str, str]]) -> str:
    return roadmap_table(
        ["Уровень", "Что видно в проекте", "Проверяемый результат"],
        [[html.escape(level), evidence, result] for level, evidence, result in rows],
    )


def roadmap_table(headers: list[str], rows: list[list[str]]) -> str:
    """Render a Chapter 24 table that becomes labelled cards on narrow screens."""
    if any(len(row) != len(headers) for row in rows):
        raise ValueError("Every roadmap-table row must match the header count")
    thead = "".join(f"<th>{html.escape(header)}</th>" for header in headers)
    tbody = "".join(
        "<tr>"
        + "".join(
            f'<td data-label="{html.escape(headers[index])}">{cell}</td>'
            for index, cell in enumerate(row)
        )
        + "</tr>"
        for row in rows
    )
    return f"""
    <div style="overflow-x:auto;margin:20px 0">
      <table class="compare-table compare-table--cards">
        <thead><tr>{thead}</tr></thead>
        <tbody>{tbody}</tbody>
      </table>
    </div>"""


