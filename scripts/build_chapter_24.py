def source_box(*source_ids: str) -> str:
    missing = [source_id for source_id in source_ids if source_id not in SOURCES]
    if missing:
        raise KeyError(f"Unknown Chapter 24 source id(s): {missing}")
    return official_sources(
        [(SOURCES[source_id]["title"], SOURCES[source_id]["url"]) for source_id in source_ids],
        adapted=False,
    )


def chapter_ref(number: int, text: str | None = None) -> str:
    target = chapter(number)
